// 平黄赤交角 ε0（度，Meeus 22.2）
inline double meanObliquityDegImpl(double jdTT)
{
    const double T = (jdTT - 2451545.0) / 36525.0;
    return 23.43929111 - 0.01300416667 * T - 1.6389e-7 * T * T
         + 5.0361e-7 * T * T * T;
}

